namespace ETLModule.Core.Models;

/// <summary>
/// Определяет стратегию разрешения конфликтов при обнаружении дублирующихся записей 
/// (совпадении первичных ключей) в процессе пакетной вставки данных.
/// </summary>
public enum ImportPolicy
{
    /// <summary>
    /// Строгий режим: при обнаружении дубликата транзакция прерывается и генерируется исключение.
    /// </summary>
    Fail,

    /// <summary>
    /// Режим пропуска: существующая в базе запись сохраняется, новая запись из файла игнорируется.
    /// </summary>
    Ignore,

    /// <summary>
    /// Режим обновления (Upsert): существующая запись перезаписывается новыми данными из файла.
    /// </summary>
    Update
}